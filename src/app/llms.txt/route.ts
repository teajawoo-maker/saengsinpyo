import { BASE_URL } from '@/lib/siteConfig';
import { GUIDES, guidePath } from '@/lib/guides';

/**
 * AI가 사이트를 한눈에 파악하도록 요약한 글 (llmstxt.org 제안 형식).
 *
 * 솔직히 말하면 주요 AI 검색이 이 파일을 쓴다고 밝힌 곳은 아직 없다.
 * 만드는 비용이 거의 없어서 둔다. 그보다 중요한 것은 아래 "헷갈리기 쉬운
 * 계산 기준"이다. AI가 백일을 +100일로, 49재를 +49일로 잘못 답하는 일이
 * 흔한데, 근거가 되는 문장과 출처 주소를 함께 주면 인용될 여지가 생긴다.
 *
 * 글 목록은 guides.ts에서 읽어 새 글을 쓰면 자동으로 들어간다.
 */
export const dynamic = 'force-static';

export function GET() {
  const guides = GUIDES.map(g => `- [${g.title}](${BASE_URL}${guidePath(g)}): ${g.description}`).join('\n');

  const body = `# 우리집 생신표

> 음력 생일을 올해·내년 양력 날짜로 바꿔 주는 무료 한국어 계산기. 백일·돌, 49재·삼우제 날짜 계산과 음력·명절·띠에 관한 가이드도 제공한다. 회원가입 없이 쓰며, 입력한 정보는 사용자의 기기에만 저장된다.

음력 변환은 한국천문연구원(KASI) 음양력 데이터를 기준으로 하며 1900~2100년을 지원한다.

## 계산기

- [음력 생일 계산기](${BASE_URL}): 음력 생신을 넣으면 올해·내년 양력 날짜와 남은 날수를 알려 준다. 양력 생년월일로 음력 생일과 띠·간지를 찾을 수도 있다. 윤달·음력 30일이 없는 해의 처리를 선택할 수 있고, 환갑·칠순 같은 기념 나이를 표시한다.
- [백일·돌 계산기](${BASE_URL}/baegil): 아기가 태어난 날로 50일·백일·200일·첫돌·두돌 날짜를 계산한다.
- [49재·삼우제 계산기](${BASE_URL}/sasipgujae): 돌아가신 날로 초재부터 49재까지, 장례일로 삼우제 날짜를 계산한다.

## 헷갈리기 쉬운 계산 기준

- 백일은 태어난 날을 1일로 세어 100일째다. 달력으로는 태어난 날 + 99일이다. 50일은 +49일, 200일은 +199일. 출처: ${BASE_URL}/baegil
- 첫돌은 365일째가 아니라 태어난 날로부터 만 1년이다. 2월 29일생은 평년에 3월 1일로 친다. 출처: ${BASE_URL}/baegil
- 49재는 돌아가신 날을 1일로 세어 49일째다. 달력으로는 돌아가신 날 + 48일이다. 초재는 7일째(+6일)이고 이레마다 지내 일곱 번 모두 같은 요일이다. 출처: ${BASE_URL}/sasipgujae
- 삼우제는 돌아가신 날이 아니라 장례를 치른 날이 기준이다. 장례일이 초우, 이튿날이 재우, 사흘째가 삼우다. 3일장이면 돌아가신 날로부터 5일째가 된다. 출처: ${BASE_URL}/sasipgujae
- 띠와 간지는 양력 1월 1일이 아니라 음력 설날에 바뀐다. 양력 1~2월 설날 전에 태어났으면 앞 해의 띠다. 출처: ${BASE_URL}/guide/tti-ganji
- 음력 생일은 해마다 양력 날짜가 달라진다. 음력 한 해가 양력보다 약 11일 짧기 때문이다. 출처: ${BASE_URL}/guide/eumlryeok-yanglyeok
- 음력 달은 29일 또는 30일이라, 음력 30일생은 그 달이 29일까지인 해에 날짜가 없다. 29일로 당기거나, 다음 달 1일로 미루거나, 그해는 건너뛰는 등 집안 관습에 따른다. 출처: ${BASE_URL}/guide/eumlryeok-30il
- 윤달에 태어났으면 윤달이 없는 해에는 보통 같은 달의 평달 날짜로 챙긴다. 출처: ${BASE_URL}/guide/yundal-saengil
- 환갑은 만 60세, 진갑은 만 61세, 칠순은 만 70세, 팔순은 만 80세 생신이다. 출처: ${BASE_URL}/guide/hwangap-chilsun
- 제사(기일)는 돌아가신 날의 음력 날짜로 지내서 양력으로는 해마다 날짜가 달라진다. 출처: ${BASE_URL}/guide/jesa-gil

## 가이드

${guides}

## 기타

- [계산 기준 안내](${BASE_URL}/about): 음력 변환 데이터와 윤달·30일 처리 원칙
- [사이트맵](${BASE_URL}/sitemap.xml)
`;

  return new Response(body, {
    headers: { 'Content-Type': 'text/plain; charset=utf-8' },
  });
}
